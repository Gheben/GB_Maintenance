#!/usr/bin/env node

const path = require('path');
const { Pool } = require('pg');
const dotenv = require('dotenv');

dotenv.config({ path: path.resolve(__dirname, '../../.env') });
dotenv.config({ path: path.resolve(__dirname, '../../backend/.env') });

const MARKER = process.env.DEMO_SEED_MARKER || 'LOCAL_DEMO_SEED_V1';

function makePool() {
  return new Pool({
    host: process.env.POSTGRES_HOST || 'localhost',
    port: parseInt(process.env.POSTGRES_PORT || '5432', 10),
    database: process.env.POSTGRES_DB || 'gbmaintenance',
    user: process.env.POSTGRES_USER || 'gbmaint',
    password: process.env.POSTGRES_PASSWORD || 'changeme',
  });
}

function ownerTargets(user) {
  return JSON.stringify([
    {
      type: 'user',
      id: user.id,
      name: user.display_name,
      email: user.email,
    },
  ]);
}

async function upsertDemoUsers(client) {
  const users = [];
  for (let i = 1; i <= 8; i += 1) {
    const username = `zz_demo_owner_${String(i).padStart(2, '0')}`;
    const displayName = `Demo Owner ${String(i).padStart(2, '0')} (${MARKER})`;
    const email = `demo.owner.${String(i).padStart(2, '0')}@demo.local`;
    const office = i % 2 === 0 ? 'ICT' : 'Direzione ICT';

    const row = await client.query(
      `INSERT INTO users (username, display_name, email, role, auth_type, office, is_active)
       VALUES ($1, $2, $3, 'operator', 'local', $4, true)
       ON CONFLICT (username) DO UPDATE
       SET display_name = EXCLUDED.display_name,
           email = EXCLUDED.email,
           office = EXCLUDED.office,
           updated_at = NOW()
       RETURNING id, username, display_name, email, office`,
      [username, displayName, email, office]
    );
    users.push(row.rows[0]);
  }
  return users;
}

async function insertDemoSuppliers(client) {
  const suppliers = [];
  for (let i = 1; i <= 10; i += 1) {
    const firstName = `Supplier${String(i).padStart(2, '0')}`;
    const lastName = 'Contact';
    const company = `Demo Supplier ${String(i).padStart(2, '0')} ${MARKER}`;
    const email = `supplier.${String(i).padStart(2, '0')}@demo.local`;
    const phone = `+39 0471 000${String(i).padStart(3, '0')}`;

    const row = await client.query(
      `INSERT INTO suppliers (first_name, last_name, company, email, phone, nationality, notes, is_active)
       VALUES ($1, $2, $3, $4, $5, 'IT', $6, true)
       RETURNING id, company`,
      [firstName, lastName, company, email, phone, `Seed marker: ${MARKER}`]
    );
    suppliers.push(row.rows[0]);
  }
  return suppliers;
}

async function insertDemoAssets(client, users) {
  const assets = [];
  const categories = ['application', 'database', 'network', 'infrastructure'];
  const criticalities = ['low', 'medium', 'high'];

  for (let i = 1; i <= 12; i += 1) {
    const owner = users[(i - 1) % users.length];
    const name = `Demo Asset ${String(i).padStart(2, '0')}`;
    const slug = `demo-asset-${String(i).padStart(2, '0')}`;

    const row = await client.query(
      `INSERT INTO assets (
         name, slug, category, criticality, description, owner_id, owner_type, owner_targets, user_targets, status, is_active
       ) VALUES (
         $1, $2, $3, $4, $5, $6, 'user', $7::jsonb, $8::jsonb, 'operational', true
       )
       ON CONFLICT (slug) DO UPDATE
       SET name = EXCLUDED.name,
           category = EXCLUDED.category,
           criticality = EXCLUDED.criticality,
           description = EXCLUDED.description,
           owner_id = EXCLUDED.owner_id,
           owner_type = EXCLUDED.owner_type,
           owner_targets = EXCLUDED.owner_targets,
           user_targets = EXCLUDED.user_targets,
           updated_at = NOW()
       RETURNING id, name, slug`,
      [
        name,
        slug,
        categories[i % categories.length],
        criticalities[i % criticalities.length],
        `Demo asset generated by ${MARKER}`,
        owner.id,
        ownerTargets(owner),
        ownerTargets(owner),
      ]
    );
    assets.push(row.rows[0]);
  }

  return assets;
}

