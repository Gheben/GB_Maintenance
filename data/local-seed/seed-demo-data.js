async function insertRelations(client, assets, services, users) {
  // Service -> Assets links (2 assets per service)
  for (let i = 0; i < services.length; i += 1) {
    const service = services[i];
    const assetA = assets[(i * 2) % assets.length];
    const assetB = assets[(i * 2 + 1) % assets.length];

    await client.query(
      `INSERT INTO service_assets (service_id, asset_id) VALUES ($1, $2) ON CONFLICT DO NOTHING`,
      [service.id, assetA.id]
    );
    await client.query(
      `INSERT INTO service_assets (service_id, asset_id) VALUES ($1, $2) ON CONFLICT DO NOTHING`,
      [service.id, assetB.id]
    );
  }

  // Asset dependencies chain
  for (let i = 1; i < assets.length; i += 1) {
    await client.query(
      `INSERT INTO asset_dependencies (asset_id, depends_on_id) VALUES ($1, $2) ON CONFLICT DO NOTHING`,
      [assets[i].id, assets[i - 1].id]
    );
  }

  // Service dependencies chain (if table exists)
  await client.query(`
    DO $$
    BEGIN
      IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_name = 'service_dependencies') THEN
        INSERT INTO service_dependencies (service_id, depends_on_id)
        SELECT s1.id, s2.id
        FROM (SELECT id, ROW_NUMBER() OVER (ORDER BY slug) rn FROM services WHERE slug LIKE 'demo-service-%') s1
        JOIN (SELECT id, ROW_NUMBER() OVER (ORDER BY slug) rn FROM services WHERE slug LIKE 'demo-service-%') s2
          ON s1.rn = s2.rn + 1
        ON CONFLICT DO NOTHING;
      END IF;
    END $$;
  `);

  // Subscribers
  for (let i = 0; i < services.length; i += 1) {
    const service = services[i];
    const user = users[(i + 2) % users.length];
    await client.query(
      `INSERT INTO service_subscribers (service_id, user_id, notify_maintenance, notify_incidents, notify_recovery)
       VALUES ($1, $2, true, true, true)
       ON CONFLICT DO NOTHING`,
      [service.id, user.id]
    );
  }
}

async function insertLicenses(client, assets, services, suppliers, users) {
  const licenses = [];

  for (let i = 1; i <= 10; i += 1) {
    const supplier = suppliers[(i - 1) % suppliers.length];
    const owner = users[(i - 1) % users.length];

    const row = await client.query(
      `INSERT INTO licenses (
         name, description, owner_user_id, supplier_id, supplier, approval_required,
         approval_status, estimated_cost, currency, notes, created_by, is_active
       ) VALUES (
         $1, $2, $3, $4, $5, true, 'approved', $6, 'EUR', $7, $8, true
       )
       RETURNING id, name`,
      [
        `Demo License ${String(i).padStart(2, '0')} ${MARKER}`,
        `Demo license generated by ${MARKER}`,
        owner.id,
        supplier.id,
        supplier.company,
        100 + i * 25,
        `Seed marker: ${MARKER}`,
        owner.id,
      ]
    );

    licenses.push(row.rows[0]);
  }

  for (let i = 0; i < licenses.length; i += 1) {
    const license = licenses[i];
    const asset = assets[i % assets.length];
    const service = services[i % services.length];

    await client.query(
      `INSERT INTO license_assets (license_id, asset_id) VALUES ($1, $2) ON CONFLICT DO NOTHING`,
      [license.id, asset.id]
    );
    await client.query(
      `INSERT INTO license_services (license_id, service_id) VALUES ($1, $2) ON CONFLICT DO NOTHING`,
      [license.id, service.id]
    );
  }
}

async function main() {
  const pool = makePool();
  const client = await pool.connect();

  try {
    await client.query('BEGIN');

    const users = await upsertDemoUsers(client);
    const suppliers = await insertDemoSuppliers(client);
    const assets = await insertDemoAssets(client, users);
    const services = await insertDemoServices(client, users);

    await insertRelations(client, assets, services, users);
    await insertLicenses(client, assets, services, suppliers, users);

    await client.query('COMMIT');

    console.log('Demo seed completed successfully.');
    console.log(`Users: ${users.length}, Suppliers: ${suppliers.length}, Assets: ${assets.length}, Services: ${services.length}, Licenses: 10`);
    console.log(`Marker: ${MARKER}`);
  } catch (err) {
    await client.query('ROLLBACK');
    console.error('Demo seed failed:', err.message);
    process.exitCode = 1;
  } finally {
    client.release();
    await pool.end();
  }
}

main();
